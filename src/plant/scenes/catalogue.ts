const ST=(inputNames:string[],outputs:string[],logic:string):string=>[
 'VAR_INPUT',...inputNames.map(v=>'  '+v+' : '+(v.endsWith('Value')?'REAL':'BOOL')+';'),'END_VAR',
 'VAR_OUTPUT',...outputs.map(v=>'  '+v+' : BOOL;'),'END_VAR',
 logic,
].join('\n');
