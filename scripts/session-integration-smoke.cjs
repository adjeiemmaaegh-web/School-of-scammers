/** Real compiled-engine session roundtrip and corruption regression. */
const assert=require('node:assert/strict');
const path=require('node:path');
const dir=process.argv[2];if(!dir)throw Error('Compiled engineering directory required');
const load=name=>require(path.join(dir,name+'.js'));
const {workcellLadder,initialWorkcell,stepWorkcell}=load('workcell');
const {newBoard}=load('wiring-board');
const {makeSession,parseSession,replaySessionTimeline,sessionFingerprint,MAX_SESSION_ACTIONS}=load('workcell-session');
const {analyzeSession}=load('session-analysis');
const actions=['isolate-power','connect-sensor','restore-power','press-start','release-start',...Array(110).fill('tick'),'open-guard','press-stop'];
const board=newBoard();
const session=makeSession('Offline exercise',workcellLadder,board,false,actions);
assert.equal(session.checkpoints.length,3);
const parsed=parseSession(JSON.stringify(session));
assert.equal(parsed.final.scan,actions.length);
const timeline=replaySessionTimeline(parsed.session.program,parsed.session.board,false,parsed.session.actions,20);
assert.equal(timeline.history.length,20);
assert.equal(timeline.firstScan,actions.length-19);
assert.equal(sessionFingerprint(timeline.final),session.fingerprint);
const direct=actions.reduce((s,a)=>stepWorkcell(s,a,20,workcellLadder),initialWorkcell());
assert.equal(sessionFingerprint(direct),session.fingerprint);
const analysis=analyzeSession(workcellLadder,board,false,actions);
assert.equal(analysis.actions,actions.length);
const tampered=structuredClone(session);tampered.checkpoints[0].fingerprint='00000000';
assert.throws(()=>parseSession(JSON.stringify(tampered)),/checkpoint mismatch/);
const tamperedAction=structuredClone(session);tamperedAction.actions[1]='open-guard';
assert.throws(()=>parseSession(JSON.stringify(tamperedAction)),/mismatch/);
assert.throws(()=>makeSession('Oversized',workcellLadder,board,false,Array(MAX_SESSION_ACTIONS+1).fill('tick')),/2000/);
console.log('PASS: 9 session replay, timeline, analysis, checkpoint and tamper checks');
